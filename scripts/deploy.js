require("dotenv").config();
const { ethers } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("====================================================");
  console.log("  DataBountyCore — BOT Chain Mainnet Deployment     ");
  console.log("====================================================");

  const [deployer] = await ethers.getSigners();
  const provider = deployer.provider;

  const network = await provider.getNetwork();
  const chainId = Number(network.chainId);
  console.log("Connected Network Chain ID:", chainId);

  if (chainId !== 677) {
    throw new Error(`Deployment aborted: Target chain ID must be 677 (BOT Chain Mainnet), got ${chainId}`);
  }

  const deployerAddress = await deployer.getAddress();
  console.log("Deployer Address:", deployerAddress);

  const balanceWei = await provider.getBalance(deployerAddress);
  const balanceEth = ethers.formatEther(balanceWei);
  console.log("Deployer Balance:", balanceEth, "BOT");

  if (balanceWei === 0n) {
    throw new Error("Deployer balance is 0 BOT. Aborting deployment.");
  }

  const initialFeeBps = 250; // 2.50% marketplace fee
  console.log(`Deploying DataBountyCore with initialFeeBps = ${initialFeeBps} (2.50%)...`);

  const DataBountyCore = await ethers.getContractFactory("DataBountyCore");

  // Deployment transaction
  const core = await DataBountyCore.deploy(initialFeeBps);
  console.log("Deployment transaction broadcasted. Tx Hash:", core.deploymentTransaction().hash);

  console.log("Waiting for confirmation on BOT Chain Mainnet...");
  await core.waitForDeployment();

  const contractAddress = await core.getAddress();
  const deployTxReceipt = await core.deploymentTransaction().wait();

  console.log("\n================ DEPLOYMENT CONFIRMED ================");
  console.log("Contract Address:", contractAddress);
  console.log("Transaction Hash:", deployTxReceipt.hash);
  console.log("Block Number:    ", deployTxReceipt.blockNumber);
  console.log("Gas Used:        ", deployTxReceipt.gasUsed.toString());
  
  const effectiveGasPrice = deployTxReceipt.gasPrice || 0n;
  const gasPriceGwei = ethers.formatUnits(effectiveGasPrice, "gwei");
  console.log("Gas Price:       ", gasPriceGwei, "gwei");

  const totalFeeWei = deployTxReceipt.gasUsed * effectiveGasPrice;
  const totalFeeBOT = ethers.formatEther(totalFeeWei);
  console.log("Total Fee Paid:  ", totalFeeBOT, "BOT");
  console.log("BOTScan Explorer: https://scan.botchain.ai/address/" + contractAddress);
  console.log("======================================================\n");

  // Post-deployment independent RPC verification
  console.log("Verifying onchain contract state via independent RPC reads...");
  const deployedCode = await provider.getCode(contractAddress);
  if (deployedCode === "0x") {
    throw new Error("Verification failed: No bytecode found at deployed contract address!");
  }
  console.log("Bytecode verified at address. Bytecode length:", deployedCode.length);

  const onchainOwner = await core.owner();
  const onchainFee = await core.feeBps();
  const maxFee = await core.MAX_FEE_BPS();

  console.log("Verified onchain state:");
  console.log("  Owner:      ", onchainOwner);
  console.log("  Fee BPS:    ", onchainFee.toString());
  console.log("  MAX Fee BPS:", maxFee.toString());

  // Save deployment artifact
  const deploymentData = {
    network: "BOT Chain Mainnet",
    chainId: 677,
    rpcUrl: "https://rpc.botchain.ai",
    explorerUrl: "https://scan.botchain.ai",
    contractName: "DataBountyCore",
    contractAddress: contractAddress,
    transactionHash: deployTxReceipt.hash,
    blockNumber: deployTxReceipt.blockNumber,
    gasUsed: deployTxReceipt.gasUsed.toString(),
    gasPriceGwei: gasPriceGwei,
    totalFeePaidBOT: totalFeeBOT,
    deployedAt: new Date().toISOString(),
    initialFeeBps: initialFeeBps,
    owner: onchainOwner,
    abi: DataBountyCore.interface.formatJson(),
  };

  const deploymentsDir = path.join(__dirname, "../deployments");
  if (!fs.existsSync(deploymentsDir)) {
    fs.mkdirSync(deploymentsDir, { recursive: true });
  }
  fs.writeFileSync(
    path.join(deploymentsDir, "botchain_mainnet.json"),
    JSON.stringify(deploymentData, null, 2)
  );
  console.log("Deployment artifact saved to deployments/botchain_mainnet.json");

  // Export to frontend configuration
  const frontendConfigDir = path.join(__dirname, "../DataBounty Frontend/src/config");
  if (!fs.existsSync(frontendConfigDir)) {
    fs.mkdirSync(frontendConfigDir, { recursive: true });
  }

  const frontendConfigContent = `// Autogenerated from BOT Chain Mainnet deployment
export const BOT_CHAIN_CONFIG = {
  chainId: 677,
  chainIdHex: "0x2a5",
  name: "BOT Chain Mainnet",
  currency: {
    name: "BOT",
    symbol: "BOT",
    decimals: 18,
  },
  rpcUrl: "https://rpc.botchain.ai",
  explorerUrl: "https://scan.botchain.ai",
  documentationUrl: "https://dev-docs.botchain.ai/docs/Developers/quick-guide/",
  contractAddress: "${contractAddress}",
  deploymentTxHash: "${deployTxReceipt.hash}",
  deploymentBlock: ${deployTxReceipt.blockNumber},
} as const;

export const DATABOUNTY_ABI = ${JSON.stringify(JSON.parse(DataBountyCore.interface.formatJson()), null, 2)} as const;
`;

  fs.writeFileSync(path.join(frontendConfigDir, "chain.ts"), frontendConfigContent);
  console.log("Frontend configuration exported to DataBounty Frontend/src/config/chain.ts");
}

main().catch((err) => {
  console.error("Mainnet deployment failed:", err);
  process.exit(1);
});
